"""Bundle existing, visible-evidence model snapshots for a file:// HTML view."""
import json
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
def build():
    read=lambda p:json.loads((ROOT/p).read_text(encoding='utf-8'))
    files = read('games/cats/model-view.json')
    actual=read(files['actual'])
    catalog=read(files['catalog'])
    cases=read(files['cases'])['cases']
    bundle=dict(actual=actual,gear=[next(g for g in catalog['equipment'] if g['id']==gid) for gid in actual['order']],
        cases=cases,tech=read(files['tech'])['ownTech'],
        upgrades=read(files['upgrades']),
        scope=files['scope'])
    (ROOT/'docs/model-view-data.js').write_text('// Generated by tools/build_model_view.py; source snapshots are preserved.\nwindow.MODEL_DATA = '+json.dumps(bundle,ensure_ascii=False,indent=2).replace('<','\\u003c')+';\n',encoding='utf-8')
    print(json.dumps(dict(parts=len(actual['placements']),ports=len(actual['portAudit']),cases=len(cases)),ensure_ascii=False))
if __name__=='__main__':build()
